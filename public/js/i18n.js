let lang = 'ar'; // Arfaj is Arabic-first; English is one tap away
try { lang = localStorage.getItem('kg_lang') || lang; } catch { /* storage blocked */ }
// A shared link can choose the language: ?lang=ar or ?lang=en
const urlLang = new URLSearchParams(location.search).get('lang');
if (urlLang === 'ar' || urlLang === 'en') {
  lang = urlLang;
  try { localStorage.setItem('kg_lang', lang); } catch { /* ignore */ }
}
if (!STRINGS[lang]) lang = 'en';

export const getLang = () => lang;

export function t(key, vars = {}) {
  const s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
}

export function applyI18n(root = document) {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  document.title = lang === 'ar' ? 'عرفج | ARFAJ' : 'Arfaj | عرفج';
}

export function setLang(next) {
  lang = STRINGS[next] ? next : 'en';
  try { localStorage.setItem('kg_lang', lang); } catch { /* ignore */ }
  applyI18n();
}
